def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


IGNORED_PARTS = frozenset({"__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache"})
WORKDIR_PREFIX = "actseal-mutants-"


def copied_files(repo: Path) -> list[Path]:
    """Every regular file the harness copies, walking without following links."""
    files: list[Path] = []
    for relative in COPIED_DIRS:
        for dirpath, dirnames, filenames in os.walk(repo / relative, followlinks=False):
            dirnames[:] = sorted(name for name in dirnames if name not in IGNORED_PARTS)
            files.extend(Path(dirpath) / name for name in sorted(filenames))
    files.extend(repo / relative for relative in COPIED_FILES)
    return files


def refuse_symlinks(repo: Path) -> None:
    """Reject any symlink among the copied inputs so a copy can never follow a link.

    Ignored cache directories are skipped. A symlinked copied directory or file,
    a symlinked subdirectory or a symlinked file anywhere beneath ``src/actseal``
    or ``tests`` is a harness error: ``copytree`` would otherwise read an
    external target or recurse into a loop.
    """
    for relative in (*COPIED_DIRS, *COPIED_FILES):
        root = repo / relative
        if root.is_symlink():
            raise HarnessError(f"copied input is a symlink: {relative}")
        if not root.exists():
            raise HarnessError(f"copied input is missing: {relative}")
    for relative in COPIED_DIRS:
        for dirpath, dirnames, filenames in os.walk(repo / relative, followlinks=False):
            dirnames[:] = [name for name in dirnames if name not in IGNORED_PARTS]
            for name in (*dirnames, *filenames):
                candidate = Path(dirpath) / name
                if candidate.is_symlink():
                    shown = candidate.relative_to(repo).as_posix()
                    raise HarnessError(f"symlink inside copied inputs: {shown}")


def tracked_source_digest(repo: Path = REPO) -> dict[str, str]:
    """SHA-256 of every file the harness copies, to prove the repository is untouched."""
    return {path.relative_to(repo).as_posix(): sha256_file(path) for path in copied_files(repo)}


def safe_parent(parent: Path, repo: Path = REPO) -> Path:
    """Resolve an existing parent directory and refuse one inside the copied sources.

    Symlinks and ``..`` are resolved first so an alias of ``src/actseal`` or
    ``tests`` is rejected while a resolved alias of a safe directory (for
    example a symlinked temporary root) stays valid.
    """
    if parent.is_symlink() and not parent.exists():
        raise HarnessError(f"workdir parent is a dangling symlink: {parent}")
    if not parent.is_dir():
        raise HarnessError(f"workdir parent must be an existing directory: {parent}")
    resolved = parent.resolve(strict=True)
    for relative in COPIED_DIRS:
        protected = (repo / relative).resolve()
        if resolved == protected or protected in resolved.parents:
            raise HarnessError(f"workdir parent {resolved} lies inside copied source {relative}")
    return resolved


def allocate_workdir(parent: Path | None, repo: Path = REPO) -> Path:
    """Create a uniquely named child the harness owns beneath a checked parent."""
    base = safe_parent(parent if parent is not None else Path(tempfile.gettempdir()), repo)
    return Path(tempfile.mkdtemp(prefix=WORKDIR_PREFIX, dir=base))


def release_workdir(workdir: Path, *, keep: bool) -> None:
    """Remove only the child this run created; the caller's parent is never touched."""
    if keep:
        emit(f"temporary trees kept under {workdir}")
        return
    if workdir.is_symlink() or not workdir.name.startswith(WORKDIR_PREFIX):
        raise HarnessError(f"refusing to remove a directory the harness did not create: {workdir}")
    shutil.rmtree(workdir, ignore_errors=True)


def run_in_owned_workdir(
    parent: Path | None, *, keep: bool, repo: Path, body: Callable[[Path], int]
) -> int:
    """Allocate an owned child, run ``body`` in it and release only that child."""
    workdir = allocate_workdir(parent, repo)
    try:
        return body(workdir)
    finally:
        release_workdir(workdir, keep=keep)


def make_tree(workdir: Path, name: str, repo: Path = REPO) -> Path:
    """Copy the package, tests and pytest configuration into ``workdir/name``."""
    refuse_symlinks(repo)
    tree = workdir / name
    for relative in COPIED_DIRS:
        shutil.copytree(repo / relative, tree / relative, ignore=IGNORED)
    for relative in COPIED_FILES:
        shutil.copy2(repo / relative, tree / relative)
    (tree / f"{PLUGIN_NAME}.py").write_text(PLUGIN_SOURCE, encoding="utf-8")
    for relative, expected in tracked_source_digest(repo).items():
        copied = tree / relative
        if not copied.is_file() or sha256_file(copied) != expected:
            raise HarnessError(f"copy of {relative} does not match the repository")
    return tree


def apply_mutation(tree: Path, mutant: Mutant, result: MutantResult) -> None:
    """Replace exactly one anchor in exactly one file; anything else invalidates."""
    target = tree / mutant.file
    original = target.read_bytes()
    result.original_sha256 = hashlib.sha256(original).hexdigest()
    anchor = mutant.anchor.encode("utf-8")
    result.anchor_count = original.count(anchor)
    if result.anchor_count != 1:
        raise HarnessError(f"anchor matched {result.anchor_count} times in {mutant.file}, need 1")
    mutated = original.replace(anchor, mutant.replacement.encode("utf-8"), 1)
    if mutated == original:
        raise HarnessError(f"mutation left {mutant.file} byte-identical")
    target.write_bytes(mutated)
    result.mutated_sha256 = hashlib.sha256(mutated).hexdigest()
    changed = [
        relative
        for relative, expected in tracked_source_digest().items()
        if sha256_file(tree / relative) != expected
    ]
    if changed != [mutant.file]:
        raise HarnessError(f"mutant changed files {changed}, expected [{mutant.file!r}]")


def child_env(tree: Path, probe_path: Path | None = None) -> dict[str, str]:
    env = dict(os.environ)
    env["PYTHONPATH"] = f"{tree / 'src'}{os.pathsep}{tree}"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env.pop("PYTEST_ADDOPTS", None)
    if probe_path is not None:
        env[PROBE_ENV] = str(probe_path)
    return env


