def all_designated_tests(mutants: Sequence[Mutant]) -> list[str]:
    seen: dict[str, None] = {}
    for mutant in mutants:
        for nodeid in mutant.tests:
            seen.setdefault(nodeid, None)
    return list(seen)


def check_baseline(run: PytestRun, mutants: Sequence[Mutant]) -> list[str]:
    """Every designated node must exist and pass in every phase on the unmutated copy."""
    problems = list(run.problems)
    if run.returncode != EXIT_OK:
        problems.append(f"baseline pytest exit {run.returncode}, expected 0")
    for mutant in mutants:
        _, missing_tests = expand_expected(mutant.tests, run.collected)
        _, missing_expected = expand_expected(mutant.expected_failures, run.collected)
        problems.extend(
            f"{mutant.mutant_id}: designated node not collected: {nodeid}"
            for nodeid in (*missing_tests, *missing_expected)
        )
    for nodeid in run.collected:
        node = run.nodes.get(nodeid)
        if node is None:
            problems.append(f"{nodeid}: no phase reports")
            continue
        problems.extend(node_problems(node))
        if node.phases.get("call") != "passed":
            problems.append(f"{nodeid}: baseline call {node.phases.get('call')}")
    return problems


def classify(result: MutantResult) -> None:
    run = result.run
    if run is None:
        result.status = "UNEXECUTED"
        return
    notes = list(run.problems)
    expected, missing = expand_expected(result.mutant.expected_failures, run.collected)
    result.expected_failures = expected
    notes.extend(f"expected node not collected: {nodeid}" for nodeid in missing)
    for nodeid in run.collected:
        node = run.nodes.get(nodeid)
        if node is None:
            notes.append(f"{nodeid}: no phase reports")
            continue
        notes.extend(node_problems(node))
        if node.assertion_failed_in_call:
            result.assertion_failures.append(nodeid)
    if result.probe is not None and not result.probe.ok:
        notes.extend(result.probe.problems)
    if notes:
        result.status = "INVALID"
        result.notes.extend(notes)
        return
    if not result.assertion_failures:
        result.status = "SURVIVED"
        result.notes.append("every designated test passed against the mutant")
        return
    survived = [nodeid for nodeid in expected if nodeid not in result.assertion_failures]
    if survived:
        result.status = "INVALID"
        result.notes.append("expected failures did not occur: " + ", ".join(survived))
        return
    result.status = "KILLED"
    extra = [nodeid for nodeid in result.assertion_failures if nodeid not in expected]
    if extra:
        result.notes.append("additional call-phase assertion failures: " + ", ".join(extra))


def run_mutant(
    workdir: Path, mutant: Mutant, baseline_fingerprint: object, timeout: float
) -> MutantResult:
    result = MutantResult(mutant, "UNEXECUTED")
    try:
        tree = make_tree(workdir, mutant.mutant_id)
        apply_mutation(tree, mutant, result)
    except HarnessError as error:
        result.status = "INVALID"
        result.notes.append(str(error))
        return result
    result.probe = run_probe(tree, timeout=timeout)
    if result.probe.ok and result.probe.data.get("fingerprint") == baseline_fingerprint:
        result.probe.ok = False
        result.probe.problems.append("mutant fingerprint equals the baseline fingerprint")
    result.run = run_pytest(tree, mutant.tests, timeout=timeout)
    classify(result)
    return result


