"""Targeted semantic mutation check for the Actseal gate (v1 Task 04).

Eight prescribed mutations of the statistical gate are applied one at a time
to *temporary copies* of the package and test tree; tracked source is never
modified. A mutant counts as killed only when every designated test fails in
its **call phase with ``AssertionError``** in a fresh interpreter whose
``actseal`` imports resolve to the temporary tree. Import, setup or lint
errors, timeouts, signals, skips, xfails and unexpected exception types never
count as kills: they invalidate the mutant.

Harness gates, in order:

1. the designated tests run unchanged against an unmutated temporary copy and
   must all pass (a baseline compile/import/setup/no-test/skip/xfail problem is
   a harness ERROR, exit 2);
2. each mutant must match exactly one anchor in exactly one file and change
   the file's bytes (reported with SHA-256 before/after);
3. a fresh subprocess probe reports the module paths it imported, the
   implementation fingerprint of the mutated tree, and that a lock sealed
   under that identity validates (locks are regenerated by the tests under the
   mutant source identity with validation enabled);
4. the designated tests run with a probe plugin that records every node's
   setup/call/teardown outcome and exception type.

Any survivor, invalid or unexecuted mutant makes the exit status nonzero.
Lint/type checks apply to the real sources only; mutants are never linted.

Temporary-tree ownership: ``--workdir`` names an existing *parent* directory
(default: the system temporary directory). It is resolved (symlinks, ``..``)
and refused when it is, or lies beneath, ``src/actseal`` or ``tests``. The run
creates one uniquely named child beneath it and removes only that child;
``--keep`` retains the child. Symlinks among the copied inputs are refused
before any copy so ``copytree`` can neither follow an external link nor
recurse.

Usage::

    uv run --frozen python tools/check_mutations.py [--only M01 ...] [--json PATH] [--keep]
"""

