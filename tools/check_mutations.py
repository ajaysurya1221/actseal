@dataclass
class NodeOutcome:
    nodeid: str
    phases: dict[str, str] = field(default_factory=dict)
    exception: str | None = None
    exception_module: str | None = None
    message: str = ""
    wasxfail: bool = False

    @property
    def assertion_failed_in_call(self) -> bool:
        return (
            self.phases.get("call") == "failed"
            and self.exception == "AssertionError"
            and self.exception_module == "builtins"
        )


