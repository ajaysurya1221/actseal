def parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Kill the eight prescribed Actseal gate mutations on temporary copies.",
        allow_abbrev=False,
    )
    parser.add_argument("--only", action="append", default=[], help="run only this mutant id")
    parser.add_argument("--json", type=Path, default=None, help="write a machine-readable report")
    parser.add_argument(
        "--workdir",
        type=Path,
        default=None,
        help=(
            "existing parent directory; the run creates and removes its own uniquely named "
            "child beneath it (default: the system temporary directory)"
        ),
    )
    parser.add_argument(
        "--keep", action="store_true", help="keep this run's child directory (never the parent)"
    )
    parser.add_argument(
        "--timeout", type=float, default=600.0, help="seconds per pytest/probe subprocess"
    )
    return parser.parse_args(argv)


def select_mutants(only: Sequence[str]) -> tuple[Mutant, ...]:
    if not only:
        return MUTANTS
    wanted = set(only)
    unknown = wanted - {mutant.mutant_id for mutant in MUTANTS}
    if unknown:
        raise HarnessError(f"unknown mutant id(s): {sorted(unknown)}")
    return tuple(mutant for mutant in MUTANTS if mutant.mutant_id in wanted)


def run_baseline(
    workdir: Path, mutants: Sequence[Mutant], timeout: float
) -> tuple[PytestRun, ProbeResult]:
    tree = make_tree(workdir, "baseline")
    probe = run_probe(tree, timeout=timeout)
    run = run_pytest(tree, all_designated_tests(mutants), timeout=timeout)
    return run, probe


def execute(args: argparse.Namespace, mutants: Sequence[Mutant], workdir: Path) -> int:
    """Baseline gate, every selected mutant, the report and the final verdict."""
    before = tracked_source_digest()
    emit(f"repository: {REPO}")
    emit(f"temporary root (owned by this run): {workdir}")
    emit(f"interpreter: {sys.executable}")
    emit()
    baseline, probe = run_baseline(workdir, mutants, args.timeout)
    emit("BASELINE (unmutated temporary copy)")
    emit(f"  probe command: {probe.command}")
    emit(f"  probe fingerprint: {probe.data.get('fingerprint', '-')}")
    for problem in probe.problems:
        emit(f"  probe problem: {problem}")
    report_run(baseline)
    problems = check_baseline(baseline, mutants) + probe.problems
    if problems:
        for problem in problems:
            emit(f"  HARNESS ERROR: {problem}")
        emit("\nRESULT: harness ERROR (baseline gate failed); no mutant was judged")
        return EXIT_HARNESS_ERROR
    emit("  baseline gate: every designated node passed setup/call/teardown\n")
    results = [
        run_mutant(workdir, mutant, probe.data.get("fingerprint"), args.timeout)
        for mutant in mutants
    ]
    for result in results:
        report_mutant(result)
    if args.json is not None:
        write_json(args.json, baseline, results)
        emit(f"json report: {args.json}")
    if tracked_source_digest() != before:
        emit("HARNESS ERROR: tracked source changed during the run")
        return EXIT_HARNESS_ERROR
    emit("tracked source unchanged (SHA-256 of every copied file re-verified)")
    counts = dict.fromkeys(("KILLED", "SURVIVED", "INVALID", "UNEXECUTED"), 0)
    for result in results:
        counts[result.status] = counts.get(result.status, 0) + 1
    emit(
        "RESULT: "
        + ", ".join(f"{count} {status.lower()}" for status, count in counts.items())
        + f" of {len(mutants)} mutant(s)"
    )
    missing = [mutant.mutant_id for mutant in MUTANTS if mutant not in mutants]
    if missing:
        emit(f"not selected this run: {', '.join(missing)}")
    if counts["KILLED"] != len(mutants) or (not args.only and len(mutants) != len(MUTANTS)):
        return EXIT_NOT_KILLED
    return EXIT_OK


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    mutants = select_mutants(args.only)
    refuse_symlinks(REPO)
    return run_in_owned_workdir(
        args.workdir,
        keep=args.keep,
        repo=REPO,
        body=lambda workdir: execute(args, mutants, workdir),
    )


if __name__ == "__main__":
    try:
        sys.exit(main())
    except HarnessError as error:
        emit(f"HARNESS ERROR: {error}")
        sys.exit(EXIT_HARNESS_ERROR)
