def run_pytest(tree: Path, nodeids: Sequence[str], *, timeout: float) -> PytestRun:
    probe_path = tree / "probe.jsonl"
    command = [
        sys.executable,
        "-m",
        "pytest",
        "-p",
        PLUGIN_NAME,
        "-p",
        "no:cacheprovider",
        "-q",
        "--no-header",
        *nodeids,
    ]
    shown = shlex.join(command)
    started = time.monotonic()
    try:
        completed = subprocess.run(  # noqa: S603 - fixed interpreter and literal node ids
            command,
            cwd=tree,
            env=child_env(tree, probe_path),
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as expired:
        run = PytestRun(
            command=shown,
            returncode=None,
            duration=time.monotonic() - started,
            timed_out=True,
            stdout_tail=_tail(expired.stdout),
            stderr_tail=_tail(expired.stderr),
            session={},
            collected=[],
            nodes={},
        )
        run.problems.append(f"pytest timed out after {timeout:.0f}s")
        return run
    run = PytestRun(
        command=shown,
        returncode=completed.returncode,
        duration=time.monotonic() - started,
        timed_out=False,
        stdout_tail=completed.stdout[-TAIL_CHARS:],
        stderr_tail=completed.stderr[-TAIL_CHARS:],
        session={},
        collected=[],
        nodes={},
    )
    if probe_path.is_file():
        parse_probe_records(probe_path.read_text(encoding="utf-8"), run)
    else:
        run.problems.append("probe plugin wrote no records")
    if run.returncode not in (EXIT_OK, PYTEST_EXIT_TESTS_FAILED):
        run.problems.append(f"pytest exit {run.returncode} (usage/collection/internal error)")
    if not run.session:
        run.problems.append("no session record: plugin did not start")
    else:
        modules = run.session.get("modules")
        if isinstance(modules, dict):
            run.problems.extend(check_module_paths(tree, modules))
        else:
            run.problems.append("session record carries no module paths")
    if not run.collected:
        run.problems.append("no tests collected")
    return run


def _tail(value: str | bytes | None) -> str:
    if value is None:
        return ""
    text = value.decode("utf-8", "replace") if isinstance(value, bytes) else value
    return text[-TAIL_CHARS:]


def parse_probe_records(text: str, run: PytestRun) -> None:
    for line in text.splitlines():
        record = json.loads(line)
        event = record.get("event")
        if event == "session":
            run.session = dict(record)
        elif event == "collected":
            run.collected = [str(item) for item in record.get("nodeids", [])]
        elif event == "report":
            node = run.nodes.setdefault(record["nodeid"], NodeOutcome(record["nodeid"]))
            when = str(record["when"])
            node.phases[when] = str(record["outcome"])
            node.wasxfail = node.wasxfail or bool(record.get("wasxfail"))
            if "exception" in record and when == "call":
                node.exception = str(record["exception"])
                node.exception_module = str(record.get("exception_module", ""))
                node.message = str(record.get("message", ""))
            elif "exception" in record and node.exception is None:
                node.exception = f"{record['exception']} during {when}"
                node.exception_module = str(record.get("exception_module", ""))
                node.message = str(record.get("message", ""))


def expand_expected(
    expected: Iterable[str], collected: Sequence[str]
) -> tuple[list[str], list[str]]:
    """Expand function-level ids to every collected parametrization; report missing ids."""
    expanded: list[str] = []
    missing: list[str] = []
    for nodeid in expected:
        if nodeid in collected:
            expanded.append(nodeid)
            continue
        matches = [item for item in collected if item.startswith(f"{nodeid}[")]
        if matches:
            expanded.extend(matches)
        else:
            missing.append(nodeid)
    return expanded, missing


def node_problems(node: NodeOutcome) -> list[str]:
    """Anything other than passed/passed/passed or a clean call-phase AssertionError."""
    problems: list[str] = []
    for phase in ("setup", "teardown"):
        outcome = node.phases.get(phase)
        if outcome != "passed":
            problems.append(f"{node.nodeid}: {phase} {outcome or 'missing'} ({node.message})")
    call = node.phases.get("call")
    if call is None:
        problems.append(f"{node.nodeid}: no call phase")
    elif call == "skipped" or node.wasxfail:
        problems.append(f"{node.nodeid}: skipped/xfail is not a kill")
    elif call == "failed" and not node.assertion_failed_in_call:
        problems.append(
            f"{node.nodeid}: call raised {node.exception_module}.{node.exception}: {node.message}"
        )
    return problems


