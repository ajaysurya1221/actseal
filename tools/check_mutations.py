def emit(line: str = "") -> None:
    sys.stdout.write(line + "\n")


def report_run(run: PytestRun, *, indent: str = "  ") -> None:
    emit(f"{indent}command: {run.command}")
    status = "timed out" if run.timed_out else f"exit {run.returncode}"
    emit(f"{indent}pytest: {status} in {run.duration:.1f}s; collected {len(run.collected)} node(s)")
    modules = run.session.get("modules") if run.session else None
    if isinstance(modules, dict):
        for name, path in sorted(modules.items()):
            emit(f"{indent}  import {name} -> {path}")
    for nodeid in run.collected:
        node = run.nodes.get(nodeid)
        if node is None:
            emit(f"{indent}  {nodeid}: NO REPORT")
            continue
        phases = "/".join(node.phases.get(phase, "-") for phase in ("setup", "call", "teardown"))
        detail = ""
        if node.exception:
            detail = f" {node.exception_module}.{node.exception}: {node.message}"
        emit(f"{indent}  {nodeid}: {phases}{detail}")
    for problem in run.problems:
        emit(f"{indent}  problem: {problem}")
    if run.timed_out or run.returncode not in (EXIT_OK, PYTEST_EXIT_TESTS_FAILED):
        emit(f"{indent}  stdout tail: {run.stdout_tail.strip()[-600:]}")
        emit(f"{indent}  stderr tail: {run.stderr_tail.strip()[-600:]}")


def report_mutant(result: MutantResult) -> None:
    mutant = result.mutant
    emit(f"{mutant.mutant_id} {result.status}: {mutant.title}")
    emit(f"  file: {mutant.file}")
    emit(f"  anchor ({result.anchor_count} match): {mutant.anchor!r}")
    emit(f"  replacement: {mutant.replacement!r}")
    emit(f"  sha256 original: {result.original_sha256 or '-'}")
    emit(f"  sha256 mutated:  {result.mutated_sha256 or '-'}")
    if result.probe is not None:
        data = result.probe.data
        emit(f"  probe command: {result.probe.command}")
        emit(f"  probe fingerprint: {data.get('fingerprint', '-')}")
        emit(
            "  probe lock regenerated under mutant identity: "
            f"implementation_sha256={data.get('lock_implementation_sha256', '-')} "
            f"validated={data.get('validated', False)}"
        )
        for problem in result.probe.problems:
            emit(f"  probe problem: {problem}")
    emit(f"  expected call-phase AssertionError nodes ({len(result.expected_failures)}):")
    for nodeid in result.expected_failures:
        emit(f"    {nodeid}")
    if result.run is not None:
        report_run(result.run)
    for note in result.notes:
        emit(f"  note: {note}")
    emit()


def write_json(path: Path, baseline: PytestRun, results: Sequence[MutantResult]) -> None:
    def run_data(run: PytestRun | None) -> dict[str, object] | None:
        if run is None:
            return None
        return {
            "command": run.command,
            "returncode": run.returncode,
            "duration_seconds": run.duration,
            "timed_out": run.timed_out,
            "session": run.session,
            "collected": run.collected,
            "nodes": {
                nodeid: {
                    "phases": node.phases,
                    "exception": node.exception,
                    "exception_module": node.exception_module,
                    "message": node.message,
                    "wasxfail": node.wasxfail,
                }
                for nodeid, node in run.nodes.items()
            },
            "problems": run.problems,
        }

    document = {
        "baseline": run_data(baseline),
        "mutants": [
            {
                "id": result.mutant.mutant_id,
                "title": result.mutant.title,
                "file": result.mutant.file,
                "anchor": result.mutant.anchor,
                "replacement": result.mutant.replacement,
                "status": result.status,
                "notes": result.notes,
                "original_sha256": result.original_sha256,
                "mutated_sha256": result.mutated_sha256,
                "anchor_count": result.anchor_count,
                "probe": None
                if result.probe is None
                else {
                    "command": result.probe.command,
                    "ok": result.probe.ok,
                    "data": result.probe.data,
                    "problems": result.probe.problems,
                },
                "expected_failures": result.expected_failures,
                "assertion_failures": result.assertion_failures,
                "run": run_data(result.run),
            }
            for result in results
        ],
    }
    path.write_text(json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8")


