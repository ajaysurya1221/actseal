def run_probe(tree: Path, *, timeout: float) -> ProbeResult:
    command = [sys.executable, "-c", PROBE_SCRIPT]
    shown = shlex.join([sys.executable, "-c", "<probe script>"])
    problems: list[str] = []
    try:
        completed = subprocess.run(  # noqa: S603 - fixed interpreter and literal script
            command,
            cwd=tree,
            env=child_env(tree),
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return ProbeResult(command=shown, ok=False, data={}, problems=["probe timed out"])
    if completed.returncode != 0:
        problems.append(f"probe exit {completed.returncode}: {completed.stderr[-TAIL_CHARS:]}")
        return ProbeResult(command=shown, ok=False, data={}, problems=problems)
    try:
        raw = json.loads(completed.stdout.strip().splitlines()[-1])
    except (ValueError, IndexError) as error:
        problems.append(f"probe output unreadable: {error}")
        return ProbeResult(command=shown, ok=False, data={}, problems=problems)
    data: dict[str, object] = dict(raw) if isinstance(raw, dict) else {}
    modules = data.get("modules")
    if not isinstance(modules, dict):
        problems.append("probe reported no module paths")
    else:
        problems.extend(check_module_paths(tree, modules))
    if data.get("fingerprint") != data.get("lock_implementation_sha256"):
        problems.append("regenerated lock does not carry the tree's fingerprint")
    if data.get("validated") is not True:
        problems.append("regenerated lock did not validate")
    return ProbeResult(command=shown, ok=not problems, data=data, problems=problems)


def check_module_paths(tree: Path, modules: Mapping[str, object]) -> list[str]:
    problems: list[str] = []
    src = (tree / "src").resolve()
    for name in ACTSEAL_MODULES:
        value = modules.get(name)
        if not isinstance(value, str):
            problems.append(f"{name}: no module path reported")
            continue
        resolved = Path(value).resolve()
        if src not in resolved.parents:
            problems.append(f"{name} imported from {value}, not from the temporary tree")
    return problems


